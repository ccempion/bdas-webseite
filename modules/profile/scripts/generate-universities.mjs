/**
 * Regenerates src/universities.generated.ts from data/hochschulen.tsv.
 *
 *   node modules/profile/scripts/generate-universities.mjs
 *
 * The TSV is the HRK Hochschulkompass export (see data/README.md). Column
 * "Adressname der Hochschule" is the common short name a student would
 * recognise ("RWTH Aachen"), as opposed to "Hochschulname", which is the long
 * legal one ("Rheinisch-Westfälische Technische Hochschule Aachen"). The short
 * name is what the dropdown shows and what we store.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "data", "hochschulen.tsv");
const TARGET = join(HERE, "..", "src", "universities.generated.ts");

const NAME_COLUMN = "Adressname der Hochschule";

/** RFC 4180 quoting with a tab delimiter — two records carry a newline inside
 *  a quoted name, so splitting on "\n" first would corrupt them. */
function parseTsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c !== '"') {
        field += c;
      } else if (text[i + 1] === '"') {
        field += '"';
        i++;
      } else {
        quoted = false;
      }
      continue;
    }
    if (c === '"') {
      quoted = true;
    } else if (c === "\t") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") {
      field += c;
    }
  }
  if (field !== "" || row.length > 0) {
    row.push(field);
    rows.push(row);
  }

  return rows.filter((r) => r.length > 1);
}

const [header, ...records] = parseTsv(readFileSync(SOURCE, "utf8"));
const nameIndex = header.indexOf(NAME_COLUMN);
if (nameIndex === -1) throw new Error(`column "${NAME_COLUMN}" missing from ${SOURCE}`);

const names = records
  .map((r) => (r[nameIndex] ?? "").replace(/\s+/g, " ").trim())
  .filter((n) => n !== "");

const duplicates = names.filter((n, i) => names.indexOf(n) !== i);
if (duplicates.length > 0) throw new Error(`duplicate names: ${duplicates.join(", ")}`);

const sorted = [...names].sort((a, b) => a.localeCompare(b, "de"));

writeFileSync(
  TARGET,
  `// Generated by scripts/generate-universities.mjs from data/hochschulen.tsv.
// Do not edit by hand — edit the TSV and regenerate.

/** Every recognised German higher-education institution, by its common short
 *  name, sorted with German collation. */
export const UNIVERSITIES: ReadonlyArray<string> = [
${sorted.map((n) => `  ${JSON.stringify(n)},`).join("\n")}
];
`,
  "utf8",
);

console.log(`wrote ${sorted.length} institutions to ${TARGET}`);
